function detectBrowserLocale(): Locale {
  const languages =
    typeof navigator === "undefined"
      ? []
      : navigator.languages.length
        ? navigator.languages
        : [navigator.language]
  return languages.some((lang) => lang.toLowerCase().startsWith("zh")) ? "zh-CN" : "en-US"
}

function storedLocaleChoice(): LocaleChoice {
  if (typeof localStorage === "undefined") return "auto"
  const value = localStorage.getItem(STORAGE_KEY)
  return value === "en-US" || value === "zh-CN" ? value : "auto"
}

const browserLocale = ref<Locale>(detectBrowserLocale())
export const localeChoice = ref<LocaleChoice>(storedLocaleChoice())
export const currentLocale = computed<Locale>(() =>
  localeChoice.value === "auto" ? browserLocale.value : localeChoice.value
)

watch(localeChoice, (value) => {
  if (typeof localStorage === "undefined") return
  if (value === "auto") {
    localStorage.removeItem(STORAGE_KEY)
  } else {
    localStorage.setItem(STORAGE_KEY, value)
  }
})

watch(
  currentLocale,
  (value) => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = value
    }
  },
  { immediate: true }
)

if (typeof window !== "undefined") {
  window.addEventListener("languagechange", () => {
    browserLocale.value = detectBrowserLocale()
  })
}

export function t(key: string, params: Record<string, string | number> = {}): string {
  const template = messages[currentLocale.value][key] ?? messages["en-US"][key] ?? key
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  )
}

export function formatDateTime(timestamp: number): string {
  return new Date(timestamp).toLocaleString(currentLocale.value, {
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit"
  })
}
